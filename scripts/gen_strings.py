def esc(t):
    t = t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    t = t.replace("'", "\\'").replace('"', '\\"')
    if t.startswith("@") or t.startswith("?"):
        t = "\\" + t
    return t

def args(t):
    return sorted(set(re.findall(r"%\d\$[sd]", t)))

used = set(sys.argv[2].split()) if len(sys.argv) > 2 else set()
missing = used - set(S)
if missing:
    sys.exit("Missing strings: " + ", ".join(sorted(missing)))
for k, (en, ar) in S.items():
    if args(en) != args(ar):
        sys.exit(f"Format args differ for {k}: {args(en)} vs {args(ar)}")

root = sys.argv[1]
for idx, folder in ((0, "values"), (1, "values-ar")):
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by scripts/gen_strings.py; edit there to keep EN/AR in sync. -->', '<resources>']
    for k, v in S.items():
        attr = ' translatable="false"' if k == "app_name" else ""
        if idx == 1 and k == "app_name":
            continue
        out.append(f'    <string name="{k}"{attr}>{esc(v[idx])}</string>')
    for k, v in P.items():
        out.append(f'    <plurals name="{k}">')
        for q, t in v[idx].items():
            out.append(f'        <item quantity="{q}">{esc(t)}</item>')
        out.append('    </plurals>')
    out.append('</resources>')
    open(f"{root}/{folder}/strings.xml", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"OK: {len(S)} strings, {len(P)} plurals, both languages")
